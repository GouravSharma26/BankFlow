export function getDemoTransactionsResponse(
  page: number = 1,
  pageSize: number = 25,
  currency?: string,
  status?: string,
  type?: string,
  channel?: string
): PaginatedTransactionsResponse {
  let filtered = [...DEMO_TRANSACTIONS];
  if (currency) {
    filtered = filtered.filter((t) => t.currency === currency);
  }
  if (status && status !== 'ALL') {
    filtered = filtered.filter((t) => t.status === status);
  }
  if (type && type !== 'ALL') {
    filtered = filtered.filter((t) => t.transaction_type === type);
  }
  if (channel && channel !== 'ALL') {
    filtered = filtered.filter((t) => t.channel === channel);
  }

  const total = filtered.length;
  const totalPages = Math.max(1, Math.ceil(total / pageSize));
  const start = (page - 1) * pageSize;
  const items = filtered.slice(start, start + pageSize);

  return {
    items,
    total,
    page,
    page_size: pageSize,
    total_pages: totalPages,
  };
}
